// «Көпір» (9 «Б» сынып, физика + информатика, құжаттық фильм)
import raw from "./audio-data.json";

export const FPS = 30;
export const sec = (s: number) => Math.round(s * FPS);

type AudioMeta = { file: string; duration: number; words: { word: string; start: number; end: number }[] };
export const AUDIO = raw as unknown as Record<string, AudioMeta>;

export const w0 = (id: string, i: number) => {
  const meta = AUDIO[id];
  if (!meta || !meta.words || !meta.words[i]) return 0;
  return meta.words[i].start;
};

